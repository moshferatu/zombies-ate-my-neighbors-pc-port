r"""Find where the game stops without playing it: generated sessions in zamn.exe.

`zamn.exe` has no 65816. When it reaches an address no port runs -- a row
whose guard turns the call down, or code with no row at all -- it prints "the
game reached $BB:AAAA, and no port runs it" and exits 3. So a session that
runs to its last frame is one the port played all of, and one that stops names
the next thing to port. This makes those sessions, many at once:

  * every level record, 0..55 (`--level`), each with every weapon, 0..13;
  * the way in is `movies/level1.zmv`'s (or `level1-2p.zmv`'s for one weapon
    in seven, with player two given a weapon and an item of their own);
  * then seeded random legs in the eight ways or standing, a few seconds
    each, with fire tapped all the while and the item used now and then;
  * health held at ten, the weapon and an item stocked, all by `--poke` from
    the frame play begins.

Every state a poke makes is one the game can be in, but `zamn_cosim verify`
still says so: a branch reached that way is checked against the ROM on a state
nothing *played* into. Replay a stopped session's `movie.zmv` with the pokes
in its `log.txt` under `verify` to see what the ROM does there.

A session shows only its *first* stop: whatever lies past it stays hidden
until that one is ported. So run it again after a round of ports, and with
other seeds (`--first-seed`), to find the next layer.

    python tools\discover.py "Zombies Ate My Neighbors.sfc" out [--jobs 12]
        [--frames 7000] [--seeds 1] [--first-seed 0] [--match L49_]

Each session gets `out\<name>\movie.zmv` and `log.txt` (the command, then what
`zamn.exe` printed); `out\results.json` has them all, and the summary lists
each address with the sessions that stopped there.
"""
import argparse
import concurrent.futures
import json
import os
import random
import re
import subprocess
import sys
import time

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DIRS = ['Up', 'Down', 'Left', 'Right', 'Up+Left', 'Up+Right', 'Down+Left',
        'Down+Right', '']
LEVELS = 56
WEAPONS = 14
ITEMS = 12
W_HEALTH = (0x1CB8, 0x1CBA)  # a word for each player
W_WEAPON = (0x1CBC, 0x1CBE)
W_ITEM = (0x1CC0, 0x1CC2)
W_AMMO = 0x1CCC   # a word for each weapon
W_COUNT = 0x1D0C  # ...and for each item
ONE_PLAYER = ('level1.zmv', 1560, 1650)  # the movie, play's first frame, the pokes'
TWO_PLAYERS = ('level1-2p.zmv', 1830, 1900)


def prefix(movie, before):
    """The movie's lines before frame `before`: its way into the game."""
    out = []
    with open(os.path.join(REPO, 'movies', movie), encoding='utf-8',
              errors='replace') as f:
        for line in f.read().splitlines():
            m = re.match(r'^(2:)?(\d+)\s', line)
            if m and int(m.group(2)) < before:
                out.append(line)
    return out


def legs(rng, start, end, pad=''):
    """Random walking from `start` to `end`, fire tapped every 14 frames."""
    out, f = [], start
    while f < end:
        way = rng.choice(DIRS)
        stop = min(f + rng.randint(15, 90), end)
        use_item = rng.random() < 0.08
        while f < stop:
            out.append('%s%d   %s' % (pad, f, way + '+Y' if way else 'Y'))
            if use_item and f + 4 < stop:
                out.append('%s%d   %s' % (pad, f + 4, way + '+X' if way else 'X'))
                use_item = False
            out.append('%s%d   %s' % (pad, f + 6, way or '-'))
            f += 14
    out.append('%s%d   -' % (pad, end))
    return out


def make_movie(path, seed, two, frames):
    rng = random.Random(seed)
    movie, play, _ = TWO_PLAYERS if two else ONE_PLAYER
    lines = prefix(movie, play) + legs(rng, play, frames - 10)
    if two:
        lines += legs(rng, play, frames - 10, pad='2:')

    # Each pad's lines in frame order.
    def key(line):
        m = re.match(r'^(2:)?(\d+)', line)
        return (1 if m.group(1) else 0, int(m.group(2)))
    lines.sort(key=key)
    with open(path, 'w', encoding='utf-8') as f:
        f.write('# generated by tools/discover.py, seed %d\n' % seed)
        f.write('\n'.join(lines) + '\n')


def poke(frame, addr, value):
    return ['--poke', '%d+:%04X=%04X' % (frame, addr, value)]


def sessions(first_seed, seeds):
    out = []
    for s in range(first_seed, first_seed + seeds):
        for level in range(LEVELS):
            for weapon in range(WEAPONS):
                two = weapon % 7 == 3
                item = (weapon + level + s) % ITEMS
                at = (TWO_PLAYERS if two else ONE_PLAYER)[2]
                pokes = (poke(at, W_HEALTH[0], 10) + poke(at, W_WEAPON[0], weapon) +
                         poke(at, W_AMMO + 2 * weapon, 0x99) +
                         poke(at, W_ITEM[0], item) + poke(at, W_COUNT + 2 * item, 9))
                if two:
                    weapon2, item2 = (weapon + 5) % WEAPONS, (item + 6) % ITEMS
                    pokes += (poke(at, W_HEALTH[1], 10) + poke(at, W_WEAPON[1], weapon2) +
                              poke(at, W_AMMO + 2 * weapon2, 0x99) +
                              poke(at, W_ITEM[1], item2) +
                              poke(at, W_COUNT + 2 * item2, 9))
                name = 'L%02d_w%02d_s%d%s' % (level, weapon, s, '_2p' if two else '')
                out.append((name, level, (s * 1000 + level) * 100 + weapon, two, pokes))
    return out


def one(rom, out, frames, session):
    name, level, seed, two, pokes = session
    d = os.path.join(out, name)
    os.makedirs(d, exist_ok=True)
    movie = os.path.join(d, 'movie.zmv')
    make_movie(movie, seed, two, frames)
    env = dict(os.environ, SDL_VIDEODRIVER='dummy', SDL_AUDIODRIVER='dummy')
    cmd = [os.path.join(REPO, 'zamn.exe'), rom, '-m', movie, '--frames',
           str(frames), '--level', str(level), '--no-config'] + pokes
    t = time.time()
    p = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                       env=env, cwd=d)
    text = p.stdout.decode('utf-8', 'replace')
    with open(os.path.join(d, 'log.txt'), 'w', encoding='utf-8') as f:
        f.write(' '.join('"%s"' % c if ' ' in c else c for c in cmd) + '\n' + text)
    m = re.search(r'the game reached \$([0-9A-F]{2}):([0-9A-F]{4})', text)
    return {'name': name, 'level': level, 'code': p.returncode,
            'stop': ('$%s:%s' % m.groups()) if m else None,
            'secs': round(time.time() - t, 1)}


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('rom')
    ap.add_argument('out')
    ap.add_argument('--jobs', type=int, default=12)
    ap.add_argument('--frames', type=int, default=7000)
    ap.add_argument('--seeds', type=int, default=1)
    ap.add_argument('--first-seed', type=int, default=0)
    ap.add_argument('--match', help='only sessions whose name this matches')
    a = ap.parse_args()
    rom = os.path.abspath(a.rom)  # each session runs in its own directory
    jobs = max(1, min(a.jobs, 12))  # more than twelve strains the machine
    todo = [s for s in sessions(a.first_seed, a.seeds)
            if not a.match or re.search(a.match, s[0])]
    os.makedirs(a.out, exist_ok=True)
    results = []
    with concurrent.futures.ThreadPoolExecutor(jobs) as pool:
        for i, r in enumerate(pool.map(lambda s: one(rom, a.out, a.frames, s), todo), 1):
            results.append(r)
            if r['stop'] or r['code'] != 0:
                print('%s code %d stop %s (%ss)' % (r['name'], r['code'], r['stop'],
                                                    r['secs']), flush=True)
            if i % 50 == 0:
                print('-- %d/%d' % (i, len(todo)), flush=True)
    with open(os.path.join(a.out, 'results.json'), 'w') as f:
        json.dump(results, f, indent=1)
    stops = {}
    for r in results:
        if r['stop']:
            stops.setdefault(r['stop'], []).append(r['name'])
    print('\n%d sessions, %d stopped, %d distinct addresses' %
          (len(results), sum(1 for r in results if r['stop']), len(stops)))
    for addr, names in sorted(stops.items(), key=lambda kv: -len(kv[1])):
        print('%s  %3d  e.g. %s' % (addr, len(names), ', '.join(names[:4])))
    for r in results:
        if r['code'] not in (0, 3):
            print('ODD', r)
    return 0


if __name__ == '__main__':
    sys.exit(main())
